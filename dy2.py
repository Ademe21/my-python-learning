# የወላጅ ክላስ (Parent Class)
class ተሽከርካሪ:

    def __init__(self, ብራንድ):
        self.ብራንድ = ብራንድ

    def እናብራ(self):
        print("ተሽከርካሪው ተነሳ! 🔑")


# የልጅ ክላስ (Child Class)
class ኤሌክትሪክ_መኪና(ተሽከርካሪ):

    def __init__(self, ብራንድ, ባትሪ_መጠን):
        super().__init__(ብራንድ)  # የወላጁን ብራንድ መውረስ
        self.ባትሪ_መጠን = ባትሪ_መጠን


# አጠቃቀም
የእኔ_ኤሌክትሪክ = ኤሌክትሪክ_መኪና("Tesla", "85kWh")
የእኔ_ኤሌክትሪክ.እናብራ()  # የወላጁን ሜተድ ተጠቀመ
